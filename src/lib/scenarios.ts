/** Номера строк (индексы), отличающиеся от исходного текста */
export function getChangedLineIndexes(text: string, original: string): Set<number> {
  const a = text.split('\n')
  const b = original.split('\n')
  const max = Math.max(a.length, b.length)
  const set = new Set<number>()
  for (let i = 0; i < max; i++) {
    if ((a[i] ?? '') !== (b[i] ?? '')) set.add(i)
  }
  return set
}

/** Количество изменённых пользователем строк */
export function countChangedLines(text: string, original: string): number {
  return getChangedLineIndexes(text, original).size
}

/** Количество шагов Gherkin (Дано/Когда/Тогда/И/То) */
export function countSteps(scenarios: Scenario[]): number {
  const step = /^(Дано|Когда|Тогда|То|И):/
  let n = 0
  scenarios.forEach((s) => {
    s.text.split('\n').forEach((l) => {
      if (step.test(l.trim())) n++
    })
  })
  return n
}

/** Собирает содержимое .feature-файла */
export function buildFeature(scenarios: Scenario[], sourceName: string): string {
  const head = sourceName.replace(/\.(docx?|txt)$/i, '') || 'техническое задание'
  const out: string[] = []
  out.push(`Feature: ${head} — сценарии Vanessa Automation`)
  out.push('')
  scenarios.forEach((s) => {
    const name = s.title.replace(/^Сценарий \d+:\s*/, '')
    out.push(`Scenario: ${name}`)
    s.text.split('\n').forEach((l) => out.push(l.trim() ? `  ${l}` : ''))
    out.push('')
  })
  return out.join('\n')
}

/** Имя .feature-файла: VanessaTestHelper_20260813_1530.feature */
export function featureFileName(): string {
  const d = new Date()
  const p = (n: number) => String(n).padStart(2, '0')
  return `VanessaTestHelper_${d.getFullYear()}${p(d.getMonth() + 1)}${p(d.getDate())}_${p(d.getHours())}${p(d.getMinutes())}.feature`
}

/** Текущее время в формате ЧЧ:ММ:СС */
export function timeStamp(): string {
  const d = new Date()
  const p = (n: number) => String(n).padStart(2, '0')
  return `${p(d.getHours())}:${p(d.getMinutes())}:${p(d.getSeconds())}`
}

/** Текущая фаза обработки по проценту прогресса */
export function progressLabel(p: number): string {
  if (p < 30) return 'Чтение файла'
  if (p < 70) return 'Идёт распознавание действий'
  if (p < 90) return 'Генерация сценариев'
  return 'Формирование .feature-файла'
}
